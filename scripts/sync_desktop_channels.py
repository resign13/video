"""Copy the web channel protocols into the standalone desktop build, without keys.

Run from any directory with Python; importing the Flask app is deliberately avoided.
"""
import ast
import copy
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "web/backend/app.py"
TARGET = ROOT / "desktop_channels.py"


class DesktopCalls(ast.NodeTransformer):
    def visit_Call(self, node):
        node = self.generic_visit(node)
        if isinstance(node.func, ast.Name):
            if node.func.id in {"upload_image_to_imgbb", "upload_image_to_uguu"}:
                node.func = ast.Attribute(ast.Name("self", ast.Load()), "upload_reference_image", ast.Load())
            elif node.func.id == "build_public_task_image_url":
                return ast.parse('self.upload_reference_image(Path(task["image_paths"][image_index]))', mode="eval").body
            elif node.func.id == "build_task_media_urls":
                node.func = ast.Attribute(ast.Name("self", ast.Load()), "upload_media", ast.Load())
        elif (isinstance(node.func, ast.Attribute) and isinstance(node.func.value, ast.Name)
              and node.func.value.id == "time" and node.func.attr == "sleep"):
            node.func = ast.Attribute(ast.Name("self", ast.Load()), "sleep", ast.Load())
        return node


def render():
    tree = ast.parse(SOURCE.read_text(encoding="utf-8-sig"))
    functions = {n.name: n for n in tree.body if isinstance(n, ast.FunctionDef)}
    constants = {n.targets[0].id: n for n in tree.body
                 if isinstance(n, ast.Assign) and isinstance(n.targets[0], ast.Name)
                 and n.targets[0].id.isupper()}
    runner = next(n for n in tree.body if isinstance(n, ast.ClassDef) and n.name == "WebTaskRunner")
    methods = [DesktopCalls().visit(copy.deepcopy(n)) for n in runner.body
               if isinstance(n, ast.FunctionDef) and n.name in {
                   "build_headers", "is_transient_request_error", "request_with_retry", "submit_task", "poll_task"}]
    selected = {"MODEL_OPTIONS", "KYY_URL_MODELS", "REFERENCE_MEDIA_FIELDS", "MEAICC_MODELS", "DOWNLOAD_RETRIES",
                "MEAICC_GENERATION_LOCK", "get_backend_config", "build_model_id", "build_request_prompt",
                "get_max_images_for_model", "get_allowed_resolutions", "get_allowed_seconds", "get_allowed_aspect_ratios",
                "upload_image_to_imgbb", "upload_image_to_uguu", "guess_mime_type"}
    selected.update(n.id for m in methods for n in ast.walk(m) if isinstance(n, ast.Name))
    pending = list(selected)
    while pending:
        name = pending.pop()
        node = functions.get(name) or constants.get(name)
        if node:
            for child in ast.walk(node):
                if isinstance(child, ast.Name) and child.id not in selected:
                    selected.add(child.id)
                    pending.append(child.id)
    body = []
    for original in tree.body:
        node = copy.deepcopy(original)
        if isinstance(node, ast.Assign) and isinstance(node.targets[0], ast.Name):
            name = node.targets[0].id
            if name not in selected or name not in constants:
                continue
            if name.endswith("API_KEY"):
                node.value = ast.Constant("")
            elif isinstance(node.value, ast.Call) and isinstance(node.value.func, ast.Name) and node.value.func.id == "env_value":
                node.value = node.value.args[1] if len(node.value.args) > 1 else ast.Constant("")
            body.append(node)
        elif isinstance(node, ast.FunctionDef) and node.name in selected:
            if node.name in {"env_value", "load_dotenv_if_present"}:
                continue
            body.append(node)
    body.append(ast.ClassDef(name="ChannelProtocol", bases=[], keywords=[], body=methods, decorator_list=[]))
    module = ast.fix_missing_locations(ast.Module(body=body, type_ignores=[]))
    header = '''# Generated by web/scripts/sync_desktop_channels.py from the web protocols.
# Desktop keys are supplied only by the local settings UI. No .env is loaded.
import base64
import json
import mimetypes
import threading
import time
from io import BytesIO
from pathlib import Path
from urllib.parse import urlparse, quote
import requests
from requests import exceptions as requests_exceptions
from PIL import Image, ImageOps

'''
    return header + ast.unparse(module) + "\n"


if __name__ == "__main__":
    TARGET.write_text(render(), encoding="utf-8")
    (ROOT / "desktop_availability.py").write_text((SOURCE.parent / "channel_availability.py").read_text(encoding="utf-8"), encoding="utf-8")
    print(f"Synced desktop channel protocols: {TARGET}")
